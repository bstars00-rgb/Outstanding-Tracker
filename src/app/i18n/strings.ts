export const STRINGS: Record<Lang, Record<StringKey, string>> = { en, ko };

export type Vars = Record<string, string | number | null | undefined>;

/** Pure translation helper (usable outside React). Falls back to English, then to the key. */
export function translate(lang: Lang, key: StringKey, vars?: Vars): string {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return vars ? fill(s, vars) : s;
}

/**
 * Label for a data enum value (e.g. `enumLabel('ko', 'invoiceStatus', 'PARTIALLY_PAID')`).
 * Unknown values fall back to the raw value with underscores replaced by spaces.
 */
export function enumLabel(lang: Lang, prefix: string, value: string | null | undefined): string {
  if (value === null || value === undefined || value === '') return '';
  const dict = STRINGS[lang] as Record<string, string>;
  return dict[`${prefix}.${value}`] ?? (STRINGS.en as Record<string, string>)[`${prefix}.${value}`] ?? value.replace(/_/g, ' ');
}
